const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const nodes = {stateMonthlyStatus: {}};
const ctx = vm.createContext({window: {}, document: {readyState: 'loading', addEventListener(){}, getElementById(id){return nodes[id] || null;}}, console});
const old = new Date(Date.now()-48*3600000).toISOString();
const fresh = new Date(Date.now()-6*3600000).toISOString();
const source = fs.readFileSync('state_monthly_ensemble.js','utf8').replace(/\}\)\(\);\s*$/, 'window.testHeader=(doc,r)=>{data=doc;renderHeader(r)};})();');
vm.runInContext(source,ctx);
const models = Object.fromEntries(['gefs','ifs','aifs','icon_eu'].map(key=>[key,{run:key==='gefs'?old:fresh,forecast_through:'2026-11-30'}]));
const region = {observed_through:'2026-11-20',observed_current:5,climatology_to_date:6,climatology_month_mean:5,models};
ctx.window.testHeader({month:11,year:2026,generated_at:fresh,observation_data_through:'2026-11-20'},region);
assert.match(nodes.stateMonthlyStatus.textContent,/GFS \/ GEFS.*veraltet/i);
assert.match(nodes.stateMonthlyStatus.className,/warn/);
ctx.window.testHeader({month:11,year:2026,generated_at:old,observation_data_through:'2026-11-20'}, {...region,models:{icon_eu:{run:old,forecast_through:'2026-11-30'}}});
assert.match(nodes.stateMonthlyStatus.textContent,/Datensatz veraltet/i);
assert.match(nodes.stateMonthlyStatus.textContent,/3.*fehlen/i);
const html=fs.readFileSync('index.html','utf8');
const badgeScript=fs.existsSync('js/dashboard-state.js')?fs.readFileSync('js/dashboard-state.js','utf8'):html;
const badgeSource=badgeScript.match(/function renderDashboardStatusBadges\(status\)\{[\s\S]*?\n\}/)[0];
nodes.statusBadges={};
vm.runInContext(badgeSource+'\nwindow.testBadges=renderDashboardStatusBadges;',ctx);
const day=new Date(Date.now()-86400000).toISOString().slice(0,10);
const ancient=new Date(Date.now()-10*86400000).toISOString().slice(0,10);
ctx.window.testBadges({daily:{latest_date:day},station_records:{data_through:ancient}});
assert.match(nodes.statusBadges.innerHTML,/class="status-badge ok"[^>]*>Tageswerte/);
assert.match(nodes.statusBadges.innerHTML,/class="status-badge warn"[^>]*>Stationsrekorde · veraltet/);
console.log('Ensemble freshness status tests passed');
